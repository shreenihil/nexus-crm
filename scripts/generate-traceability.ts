function generateCsv() {
  const header = [
    'id',
    'source_section',
    'requirement',
    'status',
    'evidence',
    'gaps',
    'severity',
    'owner_phase',
  ];

  const rows = requirements.map((item) => {
    return [
      item.id,
      `"${item.source_section.replace(/"/g, '""')}"`,
      `"${item.requirement.replace(/"/g, '""')}"`,
      item.status,
      `"${item.evidence.replace(/"/g, '""')}"`,
      `"${item.gaps.replace(/"/g, '""')}"`,
      item.severity,
      item.owner_phase,
    ].join(',');
  });

  const csvContent = [header.join(','), ...rows].join('\n');
  const targetDir = path.resolve('docs/audit');
  fs.mkdirSync(targetDir, { recursive: true });
  fs.writeFileSync(path.join(targetDir, 'traceability.csv'), csvContent, 'utf8');
  console.log(`Wrote ${requirements.length} requirements to docs/audit/traceability.csv`);
}

generateCsv();
