import { lightTheme, darkTheme, highContrastTheme } from "./semantics";
import { accentPresets } from "./themes";
import { comfortableDensity, compactDensity } from "./density";

/**
 * Compiles all design tokens into a unified CSS string of custom properties.
 */
export function compileCssVariables(): string {
  let css = "/* Autogenerated by @nexus/tokens compiler */\n\n";

  // Base Light theme
  css += ":root {\n";
  css += `  --color-bg-canvas: ${lightTheme.bgCanvas};\n`;
  css += `  --color-bg-surface: ${lightTheme.bgSurface};\n`;
  css += `  --color-bg-subtle: ${lightTheme.bgSubtle};\n`;
  css += `  --color-bg-elevated: ${lightTheme.bgElevated};\n`;
  css += `  --color-bg-overlay: ${lightTheme.bgOverlay};\n`;
  css += `  --color-text-primary: ${lightTheme.textPrimary};\n`;
  css += `  --color-text-secondary: ${lightTheme.textSecondary};\n`;
  css += `  --color-text-muted: ${lightTheme.textMuted};\n`;
  css += `  --color-text-inverse: ${lightTheme.textInverse};\n`;
  css += `  --color-border-default: ${lightTheme.borderDefault};\n`;
  css += `  --color-border-muted: ${lightTheme.borderMuted};\n`;
  css += `  --color-border-strong: ${lightTheme.borderStrong};\n`;
  css += `  --color-border-focus: ${lightTheme.borderFocus};\n`;
  css += `  --color-status-success-bg: ${lightTheme.statusSuccessBg};\n`;
  css += `  --color-status-success-text: ${lightTheme.statusSuccessText};\n`;
  css += `  --color-status-success-border: ${lightTheme.statusSuccessBorder};\n`;
  css += `  --color-status-warning-bg: ${lightTheme.statusWarningBg};\n`;
  css += `  --color-status-warning-text: ${lightTheme.statusWarningText};\n`;
  css += `  --color-status-warning-border: ${lightTheme.statusWarningBorder};\n`;
  css += `  --color-status-danger-bg: ${lightTheme.statusDangerBg};\n`;
  css += `  --color-status-danger-text: ${lightTheme.statusDangerText};\n`;
  css += `  --color-status-danger-border: ${lightTheme.statusDangerBorder};\n`;
  css += `  --color-status-info-bg: ${lightTheme.statusInfoBg};\n`;
  css += `  --color-status-info-text: ${lightTheme.statusInfoText};\n`;
  css += `  --color-status-info-border: ${lightTheme.statusInfoBorder};\n\n`;

  // Default accent (indigo)
  const defaultAccent = accentPresets.indigo!;
  css += `  --color-accent-primary: ${defaultAccent.primary};\n`;
  css += `  --color-accent-hover: ${defaultAccent.hover};\n`;
  css += `  --color-accent-active: ${defaultAccent.active};\n`;
  css += `  --color-accent-muted: ${defaultAccent.muted};\n`;
  css += `  --color-accent-text: ${defaultAccent.textOnAccent};\n\n`;

  // Default density (comfortable)
  css += `  --density-table-row: ${comfortableDensity.tableRowHeight};\n`;
  css += `  --density-cell-py: ${comfortableDensity.tableCellPaddingY};\n`;
  css += `  --density-cell-px: ${comfortableDensity.tableCellPaddingX};\n`;
  css += `  --density-input-height: ${comfortableDensity.inputHeight};\n`;
  css += `  --density-btn-height: ${comfortableDensity.buttonHeight};\n`;
  css += "}\n\n";

  // Dark Theme
  css += ".dark {\n";
  css += `  --color-bg-canvas: ${darkTheme.bgCanvas};\n`;
  css += `  --color-bg-surface: ${darkTheme.bgSurface};\n`;
  css += `  --color-bg-subtle: ${darkTheme.bgSubtle};\n`;
  css += `  --color-bg-elevated: ${darkTheme.bgElevated};\n`;
  css += `  --color-bg-overlay: ${darkTheme.bgOverlay};\n`;
  css += `  --color-text-primary: ${darkTheme.textPrimary};\n`;
  css += `  --color-text-secondary: ${darkTheme.textSecondary};\n`;
  css += `  --color-text-muted: ${darkTheme.textMuted};\n`;
  css += `  --color-text-inverse: ${darkTheme.textInverse};\n`;
  css += `  --color-border-default: ${darkTheme.borderDefault};\n`;
  css += `  --color-border-muted: ${darkTheme.borderMuted};\n`;
  css += `  --color-border-strong: ${darkTheme.borderStrong};\n`;
  css += `  --color-border-focus: ${darkTheme.borderFocus};\n`;
  css += `  --color-status-success-bg: ${darkTheme.statusSuccessBg};\n`;
  css += `  --color-status-success-text: ${darkTheme.statusSuccessText};\n`;
  css += `  --color-status-success-border: ${darkTheme.statusSuccessBorder};\n`;
  css += `  --color-status-warning-bg: ${darkTheme.statusWarningBg};\n`;
  css += `  --color-status-warning-text: ${darkTheme.statusWarningText};\n`;
  css += `  --color-status-warning-border: ${darkTheme.statusWarningBorder};\n`;
  css += `  --color-status-danger-bg: ${darkTheme.statusDangerBg};\n`;
  css += `  --color-status-danger-text: ${darkTheme.statusDangerText};\n`;
  css += `  --color-status-danger-border: ${darkTheme.statusDangerBorder};\n`;
  css += `  --color-status-info-bg: ${darkTheme.statusInfoBg};\n`;
  css += `  --color-status-info-text: ${darkTheme.statusInfoText};\n`;
  css += `  --color-status-info-border: ${darkTheme.statusInfoBorder};\n`;
  css += "}\n\n";

  // High Contrast Theme
  css += '.high-contrast, [data-theme="high-contrast"] {\n';
  css += `  --color-bg-canvas: ${highContrastTheme.bgCanvas};\n`;
  css += `  --color-bg-surface: ${highContrastTheme.bgSurface};\n`;
  css += `  --color-bg-subtle: ${highContrastTheme.bgSubtle};\n`;
  css += `  --color-bg-elevated: ${highContrastTheme.bgElevated};\n`;
  css += `  --color-bg-overlay: ${highContrastTheme.bgOverlay};\n`;
  css += `  --color-text-primary: ${highContrastTheme.textPrimary};\n`;
  css += `  --color-text-secondary: ${highContrastTheme.textSecondary};\n`;
  css += `  --color-text-muted: ${highContrastTheme.textMuted};\n`;
  css += `  --color-text-inverse: ${highContrastTheme.textInverse};\n`;
  css += `  --color-border-default: ${highContrastTheme.borderDefault};\n`;
  css += `  --color-border-muted: ${highContrastTheme.borderMuted};\n`;
  css += `  --color-border-strong: ${highContrastTheme.borderStrong};\n`;
  css += `  --color-border-focus: ${highContrastTheme.borderFocus};\n`;
  css += `  --color-status-success-bg: ${highContrastTheme.statusSuccessBg};\n`;
  css += `  --color-status-success-text: ${highContrastTheme.statusSuccessText};\n`;
  css += `  --color-status-success-border: ${highContrastTheme.statusSuccessBorder};\n`;
  css += `  --color-status-warning-bg: ${highContrastTheme.statusWarningBg};\n`;
  css += `  --color-status-warning-text: ${highContrastTheme.statusWarningText};\n`;
  css += `  --color-status-warning-border: ${highContrastTheme.statusWarningBorder};\n`;
  css += `  --color-status-danger-bg: ${highContrastTheme.statusDangerBg};\n`;
  css += `  --color-status-danger-text: ${highContrastTheme.statusDangerText};\n`;
  css += `  --color-status-danger-border: ${highContrastTheme.statusDangerBorder};\n`;
  css += `  --color-status-info-bg: ${highContrastTheme.statusInfoBg};\n`;
  css += `  --color-status-info-text: ${highContrastTheme.statusInfoText};\n`;
  css += `  --color-status-info-border: ${highContrastTheme.statusInfoBorder};\n`;
  css += "}\n\n";

  // Accents
  for (const [key, palette] of Object.entries(accentPresets)) {
    css += `[data-accent="${key}"] {\n`;
    css += `  --color-accent-primary: ${palette.primary};\n`;
    css += `  --color-accent-hover: ${palette.hover};\n`;
    css += `  --color-accent-active: ${palette.active};\n`;
    css += `  --color-accent-muted: ${palette.muted};\n`;
    css += `  --color-accent-text: ${palette.textOnAccent};\n`;
    css += "}\n\n";
  }

  // Densities
  css += '[data-density="comfortable"] {\n';
  css += `  --density-table-row: ${comfortableDensity.tableRowHeight};\n`;
  css += `  --density-cell-py: ${comfortableDensity.tableCellPaddingY};\n`;
  css += `  --density-cell-px: ${comfortableDensity.tableCellPaddingX};\n`;
  css += `  --density-input-height: ${comfortableDensity.inputHeight};\n`;
  css += `  --density-btn-height: ${comfortableDensity.buttonHeight};\n`;
  css += "}\n\n";

  css += '[data-density="compact"] {\n';
  css += `  --density-table-row: ${compactDensity.tableRowHeight};\n`;
  css += `  --density-cell-py: ${compactDensity.tableCellPaddingY};\n`;
  css += `  --density-cell-px: ${compactDensity.tableCellPaddingX};\n`;
  css += `  --density-input-height: ${compactDensity.inputHeight};\n`;
  css += `  --density-btn-height: ${compactDensity.buttonHeight};\n`;
  css += "}\n";

  return css;
}
